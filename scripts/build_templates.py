#!/usr/bin/env python3
"""
build_templates.py — 根据 config.yaml 生成内置 Word 模板

读取 templates/config.yaml 中的样式定义，基于 pandoc 默认 reference.docx
修改字体/字号/行距等样式，输出:
    1. templates/<id>.docx               — 可作为 pandoc reference-doc 使用
    2. src/core/builtin-templates.generated.ts — base64 嵌入，运行时种子数据

用法:
    python3 scripts/build_templates.py           # 从项目根目录运行
    pnpm build:templates                         # 等效 npm script

依赖:
    pip install python-docx pyyaml
"""
from __future__ import annotations

import base64
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

try:
    import yaml
except ImportError:
    print("ERROR: PyYAML not found. Please install it with `pip install pyyaml`.", file=sys.stderr)
    sys.exit(1)

# Pre-committed base reference.docx (generated by pandoc --print-default-data-file reference.docx)
# Using this avoids requiring pandoc CLI at build time.
PRECOMMITTED_BASE_DOCX = Path(__file__).resolve().parent.parent / "templates" / "pandoc-reference-base.docx"

# Verify python-docx can be imported and is functional
try:
    from docx import Document
    from docx.shared import Pt, Cm, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_LINE_SPACING
    from docx.enum.style import WD_STYLE_TYPE
    from docx.oxml.ns import qn
except ImportError:
    print("ERROR: python-docx not found. Please install it with `pip install python-docx`.", file=sys.stderr)
    sys.exit(1)

# Styles that should be created as CHARACTER type when missing
_CHAR_STYLES = {"Verbatim Char", "Body Text Char", "Footnote Reference",
                "Hyperlink", "Section Number", "Default Paragraph Font"}

# Styles that should be treated as TABLE type
_TABLE_STYLES = {"Table"}

# ---------------------------------------------------------------------------
# Path helpers
# ---------------------------------------------------------------------------
SCRIPT_DIR = Path(__file__).resolve().parent
ROOT_DIR = SCRIPT_DIR.parent
TEMPLATES_DIR = ROOT_DIR / "templates"
CONFIG_PATH = TEMPLATES_DIR / "config.yaml"
OUTPUT_TS_PATH = ROOT_DIR / "src" / "core" / "builtin-templates.generated.ts"

ALIGNMENT_MAP = {
    "left": WD_ALIGN_PARAGRAPH.LEFT,
    "center": WD_ALIGN_PARAGRAPH.CENTER,
    "right": WD_ALIGN_PARAGRAPH.RIGHT,
    "justify": WD_ALIGN_PARAGRAPH.JUSTIFY,
}


def load_config() -> dict[str, Any]:
    """Load and validate config.yaml, resolving external styles_file references."""
    if not CONFIG_PATH.exists():
        print(f"ERROR: config not found: {CONFIG_PATH}", file=sys.stderr)
        sys.exit(1)
    with open(CONFIG_PATH, encoding="utf-8") as f:
        cfg = yaml.safe_load(f)
    if "templates" not in cfg or not cfg["templates"]:
        print("ERROR: config.yaml must define at least one template", file=sys.stderr)
        sys.exit(1)

    # Resolve external style files: if a template has styles_file instead of
    # inline styles, load the referenced YAML and merge into the template dict.
    for tpl in cfg["templates"]:
        styles_file = tpl.pop("styles_file", None)
        if styles_file and "styles" not in tpl:
            styles_path = TEMPLATES_DIR / styles_file
            if not styles_path.exists():
                print(f"ERROR: styles file not found: {styles_path}", file=sys.stderr)
                sys.exit(1)
            with open(styles_path, encoding="utf-8") as f:
                styles = yaml.safe_load(f)
            if not isinstance(styles, dict):
                print(f"ERROR: styles file must be a YAML mapping: {styles_path}", file=sys.stderr)
                sys.exit(1)
            tpl["styles"] = styles

    return cfg


def generate_base_reference_doc(output_path: Path) -> None:
    """Get the default reference.docx — prefer pre-committed file, fallback to pandoc CLI."""
    if PRECOMMITTED_BASE_DOCX.exists():
        shutil.copy2(PRECOMMITTED_BASE_DOCX, output_path)
        return
    # Fallback: generate from pandoc CLI
    pandoc = shutil.which("pandoc")
    if not pandoc:
        print("ERROR: pandoc-reference-base.docx not found and pandoc not in PATH.", file=sys.stderr)
        print("  Either commit templates/pandoc-reference-base.docx or install pandoc.", file=sys.stderr)
        sys.exit(1)
    subprocess.run(
        [pandoc, "--print-default-data-file", "reference.docx"],
        stdout=open(output_path, "wb"),
        check=True,
    )


def set_run_font(run_or_rpr, *, ascii: str | None, east_asia: str | None) -> None:
    """Set font names on a run or rPr element using OOXML.

    Importantly, this also removes any theme font attributes (asciiTheme,
    hAnsiTheme, eastAsiaTheme, cstheme) that would otherwise override the
    explicit font names we set.  Pandoc's default reference.docx uses theme
    fonts on Heading styles, which is why headings revert to Calibri + 宋体
    unless the theme attributes are stripped.
    """
    # Find or create rFonts element
    rpr = run_or_rpr
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = rpr.makeelement(qn("w:rFonts"), {})
        rpr.insert(0, rfonts)
    if ascii:
        rfonts.set(qn("w:ascii"), ascii)
        rfonts.set(qn("w:hAnsi"), ascii)
        # Remove theme overrides so explicit names take effect
        for attr in (qn("w:asciiTheme"), qn("w:hAnsiTheme")):
            rfonts.attrib.pop(attr, None)
    if east_asia:
        rfonts.set(qn("w:eastAsia"), east_asia)
        rfonts.attrib.pop(qn("w:eastAsiaTheme"), None)
    # Also clear cstheme if we're setting any explicit font
    if ascii or east_asia:
        rfonts.attrib.pop(qn("w:cstheme"), None)


